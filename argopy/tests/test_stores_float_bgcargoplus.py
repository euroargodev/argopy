class TestArgoFloatOpenProductBGCArgoPlus:
    """Test that ArgoFloat.open_product routes 'BGCArgoPlus' correctly."""

    def _make_mock_argofloat(self, wmo=TEST_WMO):
        """Return a minimal ArgoFloat-like mock that exposes the real open_product method."""
        from argopy.stores.float.spec import FloatStoreProto

        af = MagicMock()
        af.WMO = wmo
        af.cache = False
        af.cachedir = ""
        af.timeout = 0
        af.open_product = FloatStoreProto.open_product.__get__(af, type(af))
        af.open_dataset = FloatStoreProto.open_dataset.__get__(af, type(af))
        af.ls_datasets = MagicMock(return_value={"prof": "dummy/6903091_prof.nc"})
        return af

    def test_registered_in_product_list(self):
        assert "BGCArgoPlus" in PRODUCT_LIST.argofloat

    def test_open_product_returns_dataset(self):
        dummy_ds = _make_dummy_dataset()
        af = self._make_mock_argofloat()

        with patch(
            STORE_CLASS,
            return_value=MagicMock(open_dataset=MagicMock(return_value=dummy_ds)),
        ):
            ds = af.open_product("BGCArgoPlus")
            assert isinstance(ds, xr.Dataset)

    def test_version_kwarg_forwarded(self):
        """version kwarg must reach BGCArgoPlusStore constructor."""
        dummy_ds = _make_dummy_dataset()
        af = self._make_mock_argofloat()
        custom_version = "v0.1_2025_12"
        mock_store_cls = MagicMock(
            return_value=MagicMock(open_dataset=MagicMock(return_value=dummy_ds))
        )

        with patch(STORE_CLASS, mock_store_cls):
            af.open_product("BGCArgoPlus", version=custom_version)
