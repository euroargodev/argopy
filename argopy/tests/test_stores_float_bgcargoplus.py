class TestBGCArgoPlusServerUnreachable:
    def test_no_connection_at_init(self):
        """Creating a store must not connect to the FTP server."""
        with patch(FTPSTORE_CLASS) as mock_ftpstore:
            store = BGCArgoPlusStore(TEST_WMO)
            assert store.url.startswith("ftp://")
            mock_ftpstore.assert_not_called()

    def test_fs_created_once(self):
        with patch(FTPSTORE_CLASS) as mock_ftpstore:
            store = BGCArgoPlusStore(TEST_WMO)
            assert store.fs is store.fs
            mock_ftpstore.assert_called_once()

    @pytest.mark.parametrize(
        "error",
        [
            ConnectionRefusedError(61, "Connection refused"),
            TimeoutError("timed out"),
            socket.gaierror(8, "nodename nor servname provided"),
            ftplib.error_temp("421 Too many connections"),
        ],
        ids=["refused", "timeout", "dns", "busy"],
    )
    def test_server_error_when_connecting(self, error):
        store = BGCArgoPlusStore(TEST_WMO)
        with patch(FTPSTORE_CLASS, side_effect=error):
            with pytest.raises(BGCArgoPlusServerError, match="Cannot reach the BGC-Argo\\+ server"):
                store.open_dataset()

    def test_server_error_when_fetching(self):
        """The connection may also drop while downloading the file."""
        store = BGCArgoPlusStore(TEST_WMO)
        _mock_fs(store).open_dataset.side_effect = ConnectionResetError(54, "Connection reset by peer")
        with pytest.raises(BGCArgoPlusServerError):
            store.open_dataset()

    def test_server_error_is_an_api_server_error(self):
        from argopy.errors import APIServerError
        assert issubclass(BGCArgoPlusServerError, APIServerError)

    def test_server_error_through_argofloat(self):
        """ArgoFloat.open_product must propagate the explicit server error."""
        from argopy.stores.float.spec import FloatStoreProto

        af = MagicMock(WMO=TEST_WMO, cache=False, cachedir="", timeout=0)
        af.open_product = FloatStoreProto.open_product.__get__(af, type(af))
        with patch(FTPSTORE_CLASS, side_effect=ConnectionRefusedError(61, "Connection refused")):
            with pytest.raises(BGCArgoPlusServerError, match="ftp.soest.hawaii.edu"):
                af.open_product("BGCArgoPlus")

    def test_server_available_checked_lazily(self):
        """Creating a store must not check the server, the check is done once on first access."""
        target = "argopy.stores.float.products.bgcargo_plus.bgcargo_plus_server_available"
        with patch(target, return_value=False) as mock_check:
            store = BGCArgoPlusStore(TEST_WMO)
            mock_check.assert_not_called()
            assert store.server_available is False
            assert store.server_available is False
            mock_check.assert_called_once()
            assert "server available : False" in repr(store)

    @pytest.mark.parametrize("reachable", [True, False])
    def test_server_available(self, reachable):
        target = "argopy.stores.float.products.bgcargo_plus.socket.create_connection"
        side_effect = None if reachable else ConnectionRefusedError(61, "Connection refused")
        with patch(target, side_effect=side_effect) as mock_conn:
            assert bgcargo_plus_server_available(timeout=1) is reachable
            mock_conn.assert_called_once()



